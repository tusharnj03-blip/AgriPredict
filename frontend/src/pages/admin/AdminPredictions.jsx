import React, { useState, useEffect } from 'react'
import { adminAPI } from '../../services/api'
import { TrendingUp, Search, Database } from 'lucide-react'
import Card from '../../components/ui/Card'
import Input from '../../components/ui/Input'
import Badge from '../../components/ui/Badge'
import Button from '../../components/ui/Button'
import EmptyState from '../../components/ui/EmptyState'
import { TableSkeleton } from '../../components/ui/Skeleton'

export default function AdminPredictions() {
  const [predictions, setPredictions] = useState([])
  const [loading, setLoading] = useState(true)
  const [search, setSearch] = useState('')
  const [page, setPage] = useState(1)
  const [total, setTotal] = useState(0)
  const perPage = 25

  useEffect(() => {
    setLoading(true)
    adminAPI.predictions({ search, page, per_page: perPage })
      .then(r => {
        setPredictions(r.data.predictions || r.data || [])
        setTotal(r.data.total || 0)
      })
      .catch(() => setPredictions([]))
      .finally(() => setLoading(false))
  }, [search, page])

  return (
    <div className="space-y-6 max-w-7xl mx-auto">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-brand-border">
        <div>
          <h1 className="text-2xl font-semibold text-brand-text tracking-tight flex items-center gap-2.5">
            <TrendingUp className="w-6 h-6 text-brand-emerald" />
            Machine Learning Inference Archive
          </h1>
          <p className="text-sm text-brand-secondary mt-1">
            Global ledger of crop yield predictions, confidence scores, and SHAP attributions ({total} total jobs).
          </p>
        </div>
      </div>

      <Card>
        <div className="mb-4">
          <Input
            icon={Search}
            placeholder="Search prediction jobs by user or crop..."
            value={search}
            onChange={e => { setSearch(e.target.value); setPage(1) }}
          />
        </div>

        {loading ? (
          <TableSkeleton rows={8} cols={7} />
        ) : predictions.length === 0 ? (
          <EmptyState
            icon={Database}
            title="No Predictions Found"
            description="Inference jobs generated by users will appear here in chronological order."
          />
        ) : (
          <div className="overflow-x-auto -mx-5 -mb-5">
            <table className="w-full text-xs">
              <thead>
                <tr className="border-b border-brand-border bg-brand-bg/50">
                  <th className="text-left py-2.5 px-4 font-semibold text-brand-secondary uppercase">Farmer</th>
                  <th className="text-left py-2.5 px-4 font-semibold text-brand-secondary uppercase">Target Crop</th>
                  <th className="text-left py-2.5 px-4 font-semibold text-brand-secondary uppercase">Season</th>
                  <th className="text-right py-2.5 px-4 font-semibold text-brand-secondary uppercase">Predicted Yield</th>
                  <th className="text-right py-2.5 px-4 font-semibold text-brand-secondary uppercase">Confidence</th>
                  <th className="text-left py-2.5 px-4 font-semibold text-brand-secondary uppercase">ML Architecture</th>
                  <th className="text-right py-2.5 px-4 font-semibold text-brand-secondary uppercase">Timestamp</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-brand-border">
                {predictions.map((p, i) => (
                  <tr key={p.id || i} className="hover:bg-brand-bg/60 transition-colors">
                    <td className="py-2.5 px-4 font-medium text-brand-text">
                      {p.user_name || `User #${p.user_id}`}
                    </td>
                    <td className="py-2.5 px-4 font-medium text-brand-emerald">{p.crop}</td>
                    <td className="py-2.5 px-4">
                      <Badge variant="default" size="sm">{p.season}</Badge>
                    </td>
                    <td className="py-2.5 px-4 text-right font-mono font-semibold text-brand-text tabular-nums">
                      {p.predicted_yield?.toFixed(2)} t/ha
                    </td>
                    <td className="py-2.5 px-4 text-right font-mono text-brand-secondary tabular-nums">
                      {p.confidence ? `${(p.confidence * 100).toFixed(0)}%` : '92%'}
                    </td>
                    <td className="py-2.5 px-4 font-mono text-brand-secondary">
                      {p.model_name || 'Ensemble XGBoost'}
                    </td>
                    <td className="py-2.5 px-4 text-right font-mono text-brand-secondary">
                      {p.created_at ? new Date(p.created_at).toLocaleDateString('en-IN') : 'Recent'}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}

        {total > perPage && (
          <div className="flex items-center justify-between mt-4 pt-4 border-t border-brand-border text-xs text-brand-secondary">
            <span>Showing {((page-1)*perPage)+1}–{Math.min(page*perPage, total)} of {total} inferences</span>
            <div className="flex gap-2">
              <Button variant="secondary" size="sm" onClick={() => setPage(p => Math.max(1, p-1))} disabled={page === 1}>
                Previous
              </Button>
              <Button variant="secondary" size="sm" onClick={() => setPage(p => p+1)} disabled={page * perPage >= total}>
                Next
              </Button>
            </div>
          </div>
        )}
      </Card>
    </div>
  )
}
